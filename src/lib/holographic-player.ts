export function adaptHolographicPlayer(
  player: PlayerPresentation,
  views: PlayerView[],
): HolographicPlayer {
  return {
    id: player.id,
    name: player.name,
    position: player.position,
    archetype: player.archetype.replace(/^[A-Z]+(?:-[A-Z]+)*\s+/, ""),
    teams: player.teams,
    portrait: player.portrait,
    originalPortrait: player.originalPortrait,
    views,
  };
}

export function createHolographicRoster(players: PlayerPresentation[]) {
  // Only athletes with an explicitly configured capture set enter this prototype.
  const captures: Record<string, PlayerView[]> = { "8": nandoViews };
  return players.flatMap((player) =>
    captures[player.id] ? [adaptHolographicPlayer(player, captures[player.id])] : [],
  );
}

export function viewClipPath(view: PlayerView) {
  return `polygon(${view.outline.map(([x, y]) => `${(x / view.width) * 100}% ${(y / view.height) * 100}%`).join(",")})`;
}
